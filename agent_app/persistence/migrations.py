def _timestamp_type(engine: Engine) -> str:
    _require_postgresql(engine)
    return "TIMESTAMP"


def _id_column_type(engine: Engine) -> str:
    _require_postgresql(engine)
    return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"


def _require_postgresql(engine: Engine) -> None:
    if engine.dialect.name != "postgresql":
        raise RuntimeError(
            f"agent_migration_postgresql_required:{engine.dialect.name}"
        )


