def ensure_agent_async_task_columns(engine: Engine) -> None:
    timestamp = _timestamp_type(engine)
    columns: dict[str, str] = {
        "max_attempts": "INTEGER NOT NULL DEFAULT 3",
        "deduplication_key": "VARCHAR(255)",
        "run_after": timestamp,
        "locked_by": "VARCHAR(160) NOT NULL DEFAULT ''",
        "locked_until": timestamp,
        "expires_at": timestamp,
    }
    with engine.begin() as connection:
        existing_columns = table_columns(connection, "agent_async_tasks")
        if not existing_columns:
            return
        for column_name, column_type in columns.items():
            if column_name in existing_columns:
                continue
            connection.execute(text(f"ALTER TABLE agent_async_tasks ADD COLUMN {column_name} {column_type}"))


